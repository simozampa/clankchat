function cleanupMachine(
  root: string,
  useClaude: boolean,
  useOpenCode: boolean,
  apply: boolean,
): boolean {
  const candidates = useOpenCode
    ? [
        'opencode.json',
        'opencode.jsonc',
        '.opencode/opencode.json',
        '.opencode/opencode.jsonc',
        '.opencode/tui.json',
        '.opencode/tui.jsonc',
      ]
    : [];
  let changed = false;
  const legacyFiles: string[] = [];
  for (const legacy of useOpenCode ? LEGACY_OPENCODE_FILES : []) {
    const target = assertSafeWritePath(root, legacy.relative);
    const content = readText(target);
    if (content === null) continue;
    const digest = createHash('sha256').update(content).digest('hex');
    if (digest !== legacy.sha256) {
      throw new ClankerChatError('SETUP_ERROR', 'A legacy OpenCode file was modified.', {
        path: target,
      });
    }
    legacyFiles.push(target);
  }
  for (const relative of candidates) {
    const target = assertSafeWritePath(root, relative);
    changed = cleanJsoncFile(target, apply) || changed;
  }
  for (const target of legacyFiles) {
    if (apply) rmSync(target, { force: true });
    changed = true;
  }

  if (useClaude) {
    const localInstructions = assertSafeWritePath(root, 'CLAUDE.local.md');
    const content = readText(localInstructions);
    if (content?.includes(LEGACY_START)) {
      const cleaned = removeOwnedBlock(
        content,
        LEGACY_INSTRUCTIONS,
        LEGACY_START,
        LEGACY_END,
        localInstructions,
      );
      if (apply) {
        if (cleaned.trim()) writeTextFileAtomic(localInstructions, `${cleaned}\n`);
        else rmSync(localInstructions, { force: true });
      }
      changed = true;
    }
  }
  return changed;
}

function commandSucceeded(result: SetupCommandResult, description: string): void {
  if (result.status === 0) return;
  throw new ClankerChatError('SETUP_ERROR', description, {
    status: result.status,
    stderr: result.stderr.trim(),
  });
}

function commandArray(result: SetupCommandResult, description: string): Record<string, unknown>[] {
  commandSucceeded(result, description);
  try {
    const errors: ParseError[] = [];
    const tree = parseTree(result.stdout, errors);
    if (errors.length > 0 || tree?.type !== 'array') throw new Error('Expected an array.');
    assertUniqueObjectKeys(tree, 'Claude Code command output');
    const value = getNodeValue(tree) as unknown[];
    if (value.some((entry) => objectValue(entry) === null)) throw new Error('Expected objects.');
    return value as Record<string, unknown>[];
  } catch (error) {
    throw new ClankerChatError('SETUP_ERROR', description, {
      cause: error instanceof Error ? error.message : String(error),
    });
  }
}

function claudeMcpOwned(result: SetupCommandResult, command: string): boolean {
  if (result.status !== 0) return false;
  const lines = result.stdout.split(/\r?\n/u);
  const field = (name: string): string | null => {
    const matches = [...result.stdout.matchAll(new RegExp(`^[ \\t]*${name}:[ \\t]*(.*)$`, 'gimu'))];
    return matches.length === 1 ? (matches[0]?.[1]?.trim() ?? '') : null;
  };
  const argsLine = lines.findIndex((line) => /^[ \t]*Args:/iu.test(line));
  const environmentLine = lines.findIndex((line) => /^[ \t]*Environment:/iu.test(line));
  const trailingEnvironment =
    environmentLine >= 0
      ? lines
          .slice(environmentLine + 1)
          .find((line) => line.trim() && !/^To remove this server,/iu.test(line.trim()))
      : undefined;
  return (
    /^Local config(?:\s+\(|$)/u.test(field('Scope') ?? '') &&
    field('Type') === 'stdio' &&
    field('Command') === command &&
    field('Args') === '' &&
    field('Environment') === '' &&
    argsLine >= 0 &&
    environmentLine === argsLine + 1 &&
    trailingEnvironment === undefined
  );
}

function inspectClaudeMcp(
  result: SetupCommandResult,
  name: 'clankerchat' | 'clankchat',
  command: 'clankerchat-mcp' | 'clankchat-mcp',
): boolean {
  if (result.status === 0) {
    if (claudeMcpOwned(result, command)) return true;
    throw new ClankerChatError(
      'SETUP_ERROR',
      `Claude Code has a conflicting or unowned ${name} MCP server.`,
    );
  }
  const output = `${result.stdout}\n${result.stderr}`;
  if (output.includes(`No MCP server named "${name}".`)) return false;
  throw new ClankerChatError(
    'SETUP_ERROR',
    `Could not inspect the Claude Code ${name} MCP server.`,
    {
      status: result.status,
      stderr: result.stderr.trim(),
    },
  );
}

function matchingEntry(
  entries: Record<string, unknown>[],
  predicate: (entry: Record<string, unknown>) => boolean,
  description: string,
): Record<string, unknown> | undefined {
  const matches = entries.filter(predicate);
  if (matches.length > 1) {
    throw new ClankerChatError('SETUP_ERROR', `Claude Code has duplicate ${description} entries.`);
  }
  return matches[0];
}

function marketplaceOwned(
  marketplace: Record<string, unknown> | undefined,
  repository: string,
  packageRoot: string,
): boolean {
  return (
    marketplace === undefined ||
    (marketplace.source === 'directory' &&
      typeof marketplace.path === 'string' &&
      path.resolve(marketplace.path) === packageRoot) ||
    (marketplace.source === 'github' && marketplace.repo === repository)
  );
}

function configureClaude(root: string, runner: NonNullable<SetupOptions['commandRunner']>): void {
  const existingMcp = runner('claude', ['mcp', 'get', 'clankerchat'], root);
  const legacyMcp = runner('claude', ['mcp', 'get', 'clankchat'], root);
  const existingMcpPresent = inspectClaudeMcp(existingMcp, 'clankerchat', 'clankerchat-mcp');
  const legacyMcpPresent = inspectClaudeMcp(legacyMcp, 'clankchat', 'clankchat-mcp');
  const packageRoot = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
  const marketplaces = commandArray(
    runner('claude', ['plugin', 'marketplace', 'list', '--json'], root),
    'Could not inspect Claude Code marketplaces.',
  );
  const marketplace = matchingEntry(
    marketplaces,
    (entry) => entry.name === 'clankerchat',
    'clankerchat marketplace',
  );
  const legacyMarketplace = matchingEntry(
    marketplaces,
    (entry) => entry.name === 'clankchat',
    'legacy clankchat marketplace',
  );
  if (!marketplaceOwned(marketplace, 'simozampa/clankerchat', packageRoot)) {
    throw new ClankerChatError(
      'SETUP_ERROR',
      'Claude Code has an unrelated clankerchat marketplace.',
    );
  }
  if (!marketplaceOwned(legacyMarketplace, 'simozampa/clankchat', packageRoot)) {
    throw new ClankerChatError(
      'SETUP_ERROR',
      'Claude Code has an unrelated legacy clankchat marketplace.',
    );
  }
  const plugins = commandArray(
    runner('claude', ['plugin', 'list', '--json'], root),
    'Could not inspect Claude Code plugins.',
  );
  const plugin = matchingEntry(
    plugins,
    (entry) => entry.id === 'clankerchat@clankerchat' && entry.scope === 'user',
    'clankerchat plugin',
  );
  const legacyPlugin = matchingEntry(
    plugins,
    (entry) => entry.id === 'clankchat@clankchat' && entry.scope === 'user',
    'legacy clankchat plugin',
  );
  if (plugin && !marketplace) {
    throw new ClankerChatError(
      'SETUP_ERROR',
      'Claude Code has a clankerchat plugin whose marketplace ownership is unknown.',
    );
  }
  if (legacyPlugin && !legacyMarketplace) {
    throw new ClankerChatError(
      'SETUP_ERROR',
      'Claude Code has a legacy clankchat plugin whose marketplace ownership is unknown.',
    );
  }
  let mcpAdded = false;
  let marketplaceAdded = false;
  let pluginInstalled = false;
  let newIntegrationReady = false;
  try {
    if (!existingMcpPresent) {
      commandSucceeded(
        runner(
          'claude',
          [
            'mcp',
            'add',
            '--scope',
            'local',
            '--transport',
            'stdio',
            'clankerchat',
            '--',
            'clankerchat-mcp',
          ],
          root,
        ),
        'Claude Code rejected the clankerchat MCP server.',
      );
      mcpAdded = true;
    }
    if (!marketplace) {
      commandSucceeded(
        runner('claude', ['plugin', 'marketplace', 'add', packageRoot], root),
        'Claude Code rejected the clankerchat marketplace.',
      );
      marketplaceAdded = true;
    }
    if (!plugin) {
      commandSucceeded(
        runner('claude', ['plugin', 'install', '--scope', 'user', 'clankerchat@clankerchat'], root),
        'Claude Code rejected the clankerchat plugin.',
      );
      pluginInstalled = true;
    } else if (plugin.version !== VERSION) {
      commandSucceeded(
        runner('claude', ['plugin', 'update', '--scope', 'user', 'clankerchat@clankerchat'], root),
        'Claude Code could not update the clankerchat plugin.',
      );
    } else if (plugin.enabled === false) {
      commandSucceeded(
        runner('claude', ['plugin', 'enable', '--scope', 'user', 'clankerchat@clankerchat'], root),
        'Claude Code could not enable the clankerchat plugin.',
      );
    }
    newIntegrationReady = true;
    if (legacyMcpPresent) {
      const rechecked = runner('claude', ['mcp', 'get', 'clankchat'], root);
      if (!inspectClaudeMcp(rechecked, 'clankchat', 'clankchat-mcp')) {
        throw new ClankerChatError(
          'SETUP_ERROR',
          'The legacy clankchat MCP server changed during setup.',
        );
      }
      commandSucceeded(
        runner('claude', ['mcp', 'remove', '--scope', 'local', 'clankchat'], root),
        'Claude Code could not remove the legacy clankchat MCP server.',
      );
    }
    if (legacyPlugin) {
      const currentMarketplaces = commandArray(
        runner('claude', ['plugin', 'marketplace', 'list', '--json'], root),
        'Could not recheck Claude Code marketplaces.',
      );
      const currentLegacyMarketplace = matchingEntry(
        currentMarketplaces,
        (entry) => entry.name === 'clankchat',
        'legacy clankchat marketplace',
      );
      const currentPlugins = commandArray(
        runner('claude', ['plugin', 'list', '--json'], root),
        'Could not recheck Claude Code plugins.',
      );
      const currentLegacyPlugin = matchingEntry(
        currentPlugins,
        (entry) => entry.id === 'clankchat@clankchat' && entry.scope === 'user',
        'legacy clankchat plugin',
      );
      if (
        !currentLegacyPlugin ||
        !currentLegacyMarketplace ||
        !marketplaceOwned(currentLegacyMarketplace, 'simozampa/clankchat', packageRoot)
      ) {
        throw new ClankerChatError(
          'SETUP_ERROR',
          'The legacy clankchat plugin changed during setup.',
        );
      }
      commandSucceeded(
        runner('claude', ['plugin', 'uninstall', '--scope', 'user', 'clankchat@clankchat'], root),
        'Claude Code could not remove the legacy clankchat plugin.',
      );
    }
    if (legacyMarketplace) {
      const currentMarketplaces = commandArray(
        runner('claude', ['plugin', 'marketplace', 'list', '--json'], root),
        'Could not recheck Claude Code marketplaces.',
      );
      const currentLegacyMarketplace = matchingEntry(
        currentMarketplaces,
        (entry) => entry.name === 'clankchat',
        'legacy clankchat marketplace',
      );
      if (
        !currentLegacyMarketplace ||
        !marketplaceOwned(currentLegacyMarketplace, 'simozampa/clankchat', packageRoot)
      ) {
        throw new ClankerChatError(
          'SETUP_ERROR',
          'The legacy clankchat marketplace changed during setup.',
        );
      }
      commandSucceeded(
        runner('claude', ['plugin', 'marketplace', 'remove', 'clankchat'], root),
        'Claude Code could not remove the legacy clankchat marketplace.',
      );
    }
  } catch (error) {
    if (!newIntegrationReady && pluginInstalled) {
      try {
        const rollbackMarketplaces = commandArray(
          runner('claude', ['plugin', 'marketplace', 'list', '--json'], root),
          'Could not recheck Claude Code marketplaces.',
        );
        const rollbackMarketplace = matchingEntry(
          rollbackMarketplaces,
          (entry) => entry.name === 'clankerchat',
          'clankerchat marketplace',
        );
        const rollbackPlugins = commandArray(
          runner('claude', ['plugin', 'list', '--json'], root),
          'Could not recheck Claude Code plugins.',
        );
        const rollbackPlugin = matchingEntry(
          rollbackPlugins,
          (entry) => entry.id === 'clankerchat@clankerchat' && entry.scope === 'user',
          'clankerchat plugin',
        );
        if (
          rollbackPlugin &&
          rollbackMarketplace &&
          marketplaceOwned(rollbackMarketplace, 'simozampa/clankerchat', packageRoot)
        ) {
          runner(
            'claude',
            ['plugin', 'uninstall', '--scope', 'user', 'clankerchat@clankerchat'],
            root,
          );
        }
      } catch {}
    }
    if (!newIntegrationReady && marketplaceAdded) {
      try {
        const rollbackMarketplaces = commandArray(
          runner('claude', ['plugin', 'marketplace', 'list', '--json'], root),
          'Could not recheck Claude Code marketplaces.',
        );
        const rollbackMarketplace = matchingEntry(
          rollbackMarketplaces,
          (entry) => entry.name === 'clankerchat',
          'clankerchat marketplace',
        );
        if (
          rollbackMarketplace &&
          marketplaceOwned(rollbackMarketplace, 'simozampa/clankerchat', packageRoot)
        ) {
          runner('claude', ['plugin', 'marketplace', 'remove', 'clankerchat'], root);
        }
      } catch {}
    }
    if (!newIntegrationReady && mcpAdded) {
      const rollbackMcp = runner('claude', ['mcp', 'get', 'clankerchat'], root);
      if (claudeMcpOwned(rollbackMcp, 'clankerchat-mcp')) {
        runner('claude', ['mcp', 'remove', '--scope', 'local', 'clankerchat'], root);
      }
    }
    throw error;
  }
}

function defaultRunner(command: string, args: string[], cwd: string): SetupCommandResult {
  const result = spawnSync(command, args, {
    cwd,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  return {
    status: result.status,
    stdout: result.stdout ?? '',
    stderr: result.stderr ?? result.error?.message ?? '',
  };
}

interface OpenCodeFiles {
  configPath: string;
  tuiPath: string;
}

function openCodeFiles(root: string): OpenCodeFiles {
  const configJson = path.join(root, '.opencode', 'opencode.json');
  const configJsonc = path.join(root, '.opencode', 'opencode.jsonc');
  if (existsSync(configJson) && existsSync(configJsonc)) {
    throw new ClankerChatError('SETUP_ERROR', 'Both OpenCode JSON and JSONC settings files exist.');
  }
  const tuiJson = path.join(root, '.opencode', 'tui.json');
  const tuiJsonc = path.join(root, '.opencode', 'tui.jsonc');
  if (existsSync(tuiJson) && existsSync(tuiJsonc)) {
    throw new ClankerChatError('SETUP_ERROR', 'Both OpenCode TUI JSON and JSONC files exist.');
  }
  return {
    configPath: existsSync(configJsonc) ? '.opencode/opencode.jsonc' : '.opencode/opencode.json',
    tuiPath: existsSync(tuiJsonc) ? '.opencode/tui.jsonc' : '.opencode/tui.json',
  };
}

function configureOpenCodeFiles(root: string, files: OpenCodeFiles, apply: boolean): void {
  configureOpenCodeServer(root, files.configPath, apply);
  addArrayValue(root, files.configPath, ['instructions'], '.opencode/clankerchat.md', apply);
  writeProjectFile(
    root,
    '.opencode/clankerchat.md',
    OPENCODE_INSTRUCTIONS,
    '<!-- generated by clankerchat -->',
    apply,
  );
  writeProjectFile(
    root,
    '.opencode/clankerchat-tui.ts',
    OPENCODE_TUI_PLUGIN,
    '// Generated by clankerchat.',
    apply,
  );
  writeProjectFile(
    root,
    '.opencode/plugins/clankerchat.ts',
    OPENCODE_CAPTURE_PLUGIN,
    '// Generated by clankerchat.',
    apply,
  );
  addArrayValue(root, files.tuiPath, ['plugin'], './clankerchat-tui.ts', apply);
}

function processIsAlive(processId: number): boolean {
  try {
    process.kill(processId, 0);
    return true;
  } catch (error) {
    return error instanceof Error && Reflect.get(error, 'code') === 'EPERM';
  }
}

function acquireSetupLock(lockPath: string): { descriptor: number; token: string } {
  let descriptor: number;
  try {
    descriptor = openSync(lockPath, 'wx', 0o600);
  } catch (error) {
    if (!(error instanceof Error) || Reflect.get(error, 'code') !== 'EEXIST') throw error;
    let owner: unknown;
    try {
      owner = JSON.parse(readFileSync(lockPath, 'utf8'));
    } catch {}
    const processId =
      typeof owner === 'object' && owner !== null ? Reflect.get(owner, 'processId') : undefined;
    const active =
      typeof processId === 'number' && Number.isInteger(processId) && processIsAlive(processId);
    throw new ClankerChatError(
      'SETUP_ERROR',
      active
        ? 'Another clankerchat setup is already running.'
        : 'A previous setup left a lock; remove it only after confirming no setup is running.',
      { lockPath },
    );
  }
  const token = `${JSON.stringify({ processId: process.pid, startedAt: Date.now() })}\n`;
  try {
    writeFileSync(descriptor, token);
  } catch (error) {
    closeSync(descriptor);
    rmSync(lockPath, { force: true });
    throw error;
  }
  return { descriptor, token };
}

export function setup(options: SetupOptions = {}): SetupResult {
  let repository = resolveRepository(options.cwd);
  const configureAll =
    options.claude === undefined && options.codex === undefined && options.opencode === undefined;
  const useClaude = configureAll || options.claude === true;
  const useOpenCode = configureAll || options.opencode === true;
  const home = options.homeDirectory ?? os.homedir();
  const runner = options.commandRunner ?? defaultRunner;
  const codexHome = codexHomeDirectory(home, options.homeDirectory !== undefined);
  const initialStateDirectory = path.dirname(repository.databasePath);
  if (existsSync(initialStateDirectory) && lstatSync(initialStateDirectory).isSymbolicLink()) {
    throw new ClankerChatError('SETUP_ERROR', 'Refusing to use a symlinked state directory.', {
      path: initialStateDirectory,
    });
  }
  mkdirSync(initialStateDirectory, { recursive: true, mode: 0o700 });
  const lockPath = path.join(initialStateDirectory, 'setup.lock');
  const lock = acquireSetupLock(lockPath);
  let codexLock: { descriptor: number; token: string; path: string } | null = null;

  try {
    const inspectedCodex =
      configureAll || options.codex === true
        ? runner('codex', ['--version'], repository.root)
        : null;
    if (options.codex === true && inspectedCodex) assertCodexVersion(inspectedCodex);
    const inspectedHooks =
      inspectedCodex?.status === 0 && codexVersionSupported(inspectedCodex.stdout)
        ? runner('codex', ['features', 'list'], repository.root)
        : null;
    if (options.codex === true && inspectedHooks) assertCodexHooksEnabled(inspectedHooks);
    const useCodex =
      options.codex === true ||
      (configureAll &&
        inspectedCodex?.status === 0 &&
        codexVersionSupported(inspectedCodex.stdout) &&
        inspectedHooks?.status === 0 &&
        codexHooksFeatureEnabled(inspectedHooks.stdout));

    // Harness inspection can run user commands, so resolve state again before creating a database.
    repository = resolveRepository(repository.root);
    const stateDirectory = path.dirname(repository.databasePath);
    if (existsSync(stateDirectory) && lstatSync(stateDirectory).isSymbolicLink()) {
      throw new ClankerChatError('SETUP_ERROR', 'Refusing to use a symlinked state directory.', {
        path: stateDirectory,
      });
    }
    mkdirSync(stateDirectory, { recursive: true, mode: 0o700 });
    if (useCodex) {
      if (existsSync(codexHome) && lstatSync(codexHome).isSymbolicLink()) {
        throw new ClankerChatError('SETUP_ERROR', 'Refusing to use a symlinked Codex home.', {
          path: codexHome,
        });
      }
      mkdirSync(codexHome, { recursive: true, mode: 0o700 });
      const codexLockPath = assertSafeWritePath(codexHome, 'clankchat-setup.lock');
      codexLock = { ...acquireSetupLock(codexLockPath), path: codexLockPath };
    }
    const database = openDatabase(repository.databasePath);
    database.close();
    cleanupMachine(repository.root, useClaude, useOpenCode, false);
    const configured: string[] = [];
    const localPath = 'CLAUDE.local.md';
    const target = path.join(repository.root, localPath);
    const current = useClaude
      ? removeOwnedBlock(
          removeOwnedBlock(readText(target) ?? '', INSTRUCTIONS, OWNED_START, OWNED_END, target),
          LEGACY_INSTRUCTIONS,
          LEGACY_START,
          LEGACY_END,
          target,
        )
      : '';
    const claudeContent = `${current.trimEnd()}${current.trim() ? '\n\n' : ''}${INSTRUCTIONS}`;
    if (useClaude) writeProjectFile(repository.root, localPath, claudeContent, undefined, false);
    if (useCodex) {
      configureCodexHooks(codexHome, false);
      configureCodexProject(repository.root, false);
    }
    const openCode = useOpenCode ? openCodeFiles(repository.root) : null;
    if (openCode) configureOpenCodeFiles(repository.root, openCode, false);

    if (useClaude) {
      configureClaude(repository.root, runner);
      writeProjectFile(repository.root, localPath, claudeContent);
      configured.push('claude-code');
    }

    if (useCodex) {
      configureCodex(repository.root, codexHome);
      configured.push('codex');
    }

    if (openCode) {
      configureOpenCodeFiles(repository.root, openCode, true);
      configured.push('opencode');
    }

    const removedStaleConfiguration = cleanupMachine(repository.root, useClaude, useOpenCode, true);

    return {
      repositoryRoot: repository.root,
      databasePath: repository.databasePath,
      configured,
      removedStaleConfiguration,
      restartRequired: [...configured],
    };
  } finally {
    if (codexLock) {
      closeSync(codexLock.descriptor);
      if (readText(codexLock.path) === codexLock.token) rmSync(codexLock.path, { force: true });
    }
    closeSync(lock.descriptor);
    if (readText(lockPath) === lock.token) rmSync(lockPath, { force: true });
  }
}
