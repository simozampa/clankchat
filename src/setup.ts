function readText(target: string): string | null {
  try {
    return readFileSync(target, 'utf8');
  } catch (error) {
    if (error instanceof Error && Reflect.get(error, 'code') === 'ENOENT') return null;
    throw error;
  }
}

function writeProjectFile(
  root: string,
  relative: string,
  content: string,
  ownedMarker?: string,
  apply = true,
): boolean {
  const target = assertSafeWritePath(root, relative);
  const existing = readText(target);
  if (existing === content) return false;
  if (existing !== null && ownedMarker) {
    throw new ClankerChatError(
      'SETUP_ERROR',
      'Refusing to overwrite an unowned integration file.',
      {
        path: target,
      },
    );
  }
  if (apply) {
    mkdirSync(path.dirname(target), { recursive: true });
    writeTextFileAtomic(target, content);
  }
  return true;
}

function removeKnownBlock(
  content: string,
  expected: string,
  start: string,
  end: string,
  target: string,
): string {
  let updated = content;
  while (updated.includes(start) || updated.includes(end)) {
    const begin = updated.indexOf(start);
    const finish = updated.indexOf(end);
    if (begin < 0 || finish < begin) {
      throw new ClankerChatError('SETUP_ERROR', 'An integration marker is malformed.', {
        path: target,
      });
    }
    const marked = updated.slice(begin, finish + end.length);
    if (marked !== expected.trimEnd()) {
      throw new ClankerChatError('SETUP_ERROR', 'A marked integration block was modified.', {
        path: target,
      });
    }
    updated = `${updated.slice(0, begin)}${updated.slice(finish + end.length)}`;
  }
  return updated;
}

function removeOwnedBlock(
  content: string,
  expected: string,
  start: string,
  end: string,
  target: string,
): string {
  return removeKnownBlock(content, expected, start, end, target)
    .replace(/\n{3,}/gu, '\n\n')
    .trimEnd();
}

interface CleanupEdit {
  path: Array<string | number>;
  value: unknown;
}

function objectValue(value: unknown): Record<string, unknown> | null {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

function hasOnlyKeys(value: Record<string, unknown>, allowed: string[]): boolean {
  return Object.keys(value).every((key) => allowed.includes(key));
}

function ownedOpenCodeRegistration(
  value: unknown,
  command: string,
  environmentKey: string,
): boolean {
  const registration = objectValue(value);
  if (
    !registration ||
    Object.keys(registration).length !== 5 ||
    !hasOnlyKeys(registration, ['type', 'command', 'environment', 'enabled', 'timeout'])
  ) {
    return false;
  }
  if (registration.type !== 'local') return false;
  if (
    !Array.isArray(registration.command) ||
    registration.command.length !== 1 ||
    registration.command[0] !== command
  ) {
    return false;
  }
  const entries = objectValue(registration.environment);
  if (!entries || Object.keys(entries).length !== 1 || entries[environmentKey] !== 'opencode') {
    return false;
  }
  return registration.enabled === true && registration.timeout === OPENCODE_TIMEOUT_MS;
}

function staleRegistrationEdit(
  container: Record<string, unknown>,
  name: 'sametree' | 'clankchat',
  current: Array<string | number>,
  target: string,
  owned: (value: unknown) => boolean,
): CleanupEdit[] {
  if (container[name] === undefined) return [];
  if (!owned(container[name])) {
    throw new ClankerChatError('SETUP_ERROR', 'Refusing to remove an unowned legacy integration.', {
      path: target,
      integration: name,
    });
  }
  return [{ path: [...current, name], value: undefined }];
}

function removeExactArrayValues(
  object: Record<string, unknown>,
  key: string,
  values: string[],
): CleanupEdit[] {
  const entries = object[key];
  if (!Array.isArray(entries)) return [];
  return entries
    .flatMap((entry, index) => (typeof entry === 'string' && values.includes(entry) ? [index] : []))
    .sort((left, right) => right - left)
    .map((index) => ({ path: [key, index], value: undefined }));
}

function openCodeCleanupEdits(value: unknown, target: string): CleanupEdit[] {
  const object = objectValue(value);
  if (!object) return [];
  const edits: CleanupEdit[] = [];
  const servers = objectValue(object.mcp);
  if (servers) {
    edits.push(
      ...staleRegistrationEdit(servers, 'clankchat', ['mcp'], target, (candidate) =>
        ownedOpenCodeRegistration(candidate, 'clankchat-mcp', 'CLANKCHAT_HARNESS'),
      ),
    );
  }
  edits.push(
    ...removeExactArrayValues(object, 'instructions', ['.opencode/clankchat.md']),
    ...removeExactArrayValues(object, 'plugin', ['./clankchat-tui.ts']),
  );
  return edits;
}

function cleanJsoncFile(target: string, apply: boolean): boolean {
  const content = readText(target);
  if (
    content === null ||
    (!content.toLowerCase().includes('sametree') && !content.toLowerCase().includes('clankchat'))
  )
    return false;
  if (lstatSync(target).isSymbolicLink()) {
    throw new ClankerChatError('SETUP_ERROR', 'Refusing to update a symlinked settings file.', {
      path: target,
    });
  }
  const value = parseJsonc(content, target);
  let updated = content;
  const edits = openCodeCleanupEdits(value, target).sort(
    (left, right) => right.path.length - left.path.length,
  );
  if (edits.length === 0) return false;
  for (const edit of edits) {
    updated = applyEdits(
      updated,
      modify(updated, edit.path, edit.value, {
        formattingOptions: { insertSpaces: true, tabSize: 2 },
      }),
    );
  }
  if (updated === content) return false;
  if (apply) writeTextFileAtomic(target, updated);
  return true;
}

function setJsoncValue(
  root: string,
  relative: string,
  targetPath: Array<string | number>,
  value: unknown,
  apply = true,
): boolean {
  const target = assertSafeWritePath(root, relative);
  const original = readText(target) ?? '{}\n';
  parseJsonc(original, target);
  const updated = applyEdits(
    original,
    modify(original, targetPath, value, {
      formattingOptions: { insertSpaces: true, tabSize: 2 },
    }),
  );
  if (updated === original && existsSync(target)) return false;
  if (apply) {
    mkdirSync(path.dirname(target), { recursive: true });
    writeTextFileAtomic(target, updated.endsWith('\n') ? updated : `${updated}\n`);
  }
  return true;
}

function parseJsonc(content: string, target: string): unknown {
  const errors: ParseError[] = [];
  const tree = parseTree(content, errors, { allowTrailingComma: true });
  if (errors.length > 0 || tree?.type !== 'object') {
    throw new ClankerChatError('SETUP_ERROR', 'Could not parse an integration settings file.', {
      path: target,
    });
  }
  assertUniqueObjectKeys(tree, target);
  return getNodeValue(tree) as unknown;
}

function assertUniqueObjectKeys(node: Node, target: string): void {
  if (node.type === 'object') {
    const seen = new Set<string>();
    for (const property of node.children ?? []) {
      const key = String(property.children?.[0]?.value);
      if (seen.has(key)) {
        throw new ClankerChatError('SETUP_ERROR', 'A settings file has duplicate keys.', {
          path: target,
          key,
        });
      }
      seen.add(key);
      const value = property.children?.[1];
      if (value) assertUniqueObjectKeys(value, target);
    }
    return;
  }
  if (node.type === 'array') {
    for (const child of node.children ?? []) assertUniqueObjectKeys(child, target);
  }
}

function nestedValue(value: unknown, targetPath: string[]): unknown {
  let current = value;
  for (const segment of targetPath) {
    current =
      typeof current === 'object' && current !== null ? Reflect.get(current, segment) : undefined;
  }
  return current;
}

function addArrayValue(
  root: string,
  relative: string,
  targetPath: string[],
  value: string,
  apply = true,
): boolean {
  const target = assertSafeWritePath(root, relative);
  const original = readText(target) ?? '{}\n';
  const current = nestedValue(parseJsonc(original, target), targetPath);
  if (current !== undefined && !Array.isArray(current)) {
    throw new ClankerChatError('SETUP_ERROR', 'An integration list has an incompatible value.', {
      path: target,
      setting: targetPath.join('.'),
    });
  }
  const entries = current ?? [];
  if (
    entries.some(
      (entry) =>
        entry === value || (Array.isArray(entry) && entry.length > 0 && entry[0] === value),
    )
  )
    return false;
  return setJsoncValue(
    root,
    relative,
    current === undefined ? targetPath : [...targetPath, entries.length],
    current === undefined ? [value] : value,
    apply,
  );
}

function configureOpenCodeServer(root: string, relative: string, apply = true): boolean {
  const target = assertSafeWritePath(root, relative);
  const original = readText(target) ?? '{}\n';
  const current = nestedValue(parseJsonc(original, target), ['mcp', 'clankerchat']);
  if (current !== undefined && JSON.stringify(current) !== JSON.stringify(MCP_SERVER)) {
    throw new ClankerChatError(
      'SETUP_ERROR',
      'OpenCode already has a conflicting clankerchat MCP server.',
      { path: target },
    );
  }
  return setJsoncValue(root, relative, ['mcp', 'clankerchat'], MCP_SERVER, apply);
}

function configureCodexProject(root: string, apply: boolean): boolean {
  const target = assertSafeWritePath(root, '.codex/config.toml');
  const existing = readText(target) ?? '';
  const original = removeKnownBlock(
    existing,
    LEGACY_CODEX_PROJECT_BLOCK,
    '# clankchat:start',
    '# clankchat:end',
    target,
  );
  const start = original.indexOf(CODEX_PROJECT_START);
  const end = original.indexOf(CODEX_PROJECT_END);
  if (
    start < 0 !== end < 0 ||
    (start >= 0 &&
      (end < start ||
        original.indexOf(CODEX_PROJECT_START, start + CODEX_PROJECT_START.length) >= 0 ||
        original.indexOf(CODEX_PROJECT_END, end + CODEX_PROJECT_END.length) >= 0))
  ) {
    throw new ClankerChatError('SETUP_ERROR', 'The Codex integration marker is malformed.', {
      path: target,
    });
  }
  let updated: string;
  if (start >= 0) {
    const marked = original.slice(start, end + CODEX_PROJECT_END.length);
    if (marked !== CODEX_PROJECT_BLOCK) {
      throw new ClankerChatError('SETUP_ERROR', 'The Codex integration block was modified.', {
        path: target,
      });
    }
    updated = `${original.slice(0, start)}${CODEX_PROJECT_BLOCK}${original.slice(
      end + CODEX_PROJECT_END.length,
    )}`;
  } else {
    let parsed: Record<string, unknown>;
    try {
      parsed = parseToml(original) as Record<string, unknown>;
    } catch (error) {
      throw new ClankerChatError('SETUP_ERROR', 'Could not parse the Codex configuration.', {
        path: target,
        cause: error instanceof Error ? error.message : String(error),
      });
    }
    const servers = parsed.mcp_servers;
    if (typeof servers === 'object' && servers !== null) {
      const conflicting = ['clankerchat', 'clankchat'].find(
        (name) => Reflect.get(servers, name) !== undefined,
      );
      if (!conflicting) {
        updated = `${original.trimEnd()}${original.trim() ? '\n\n' : ''}${CODEX_PROJECT_BLOCK}\n`;
      } else {
        throw new ClankerChatError(
          'SETUP_ERROR',
          `Codex already has a conflicting ${conflicting} MCP server.`,
          { path: target },
        );
      }
    } else {
      updated = `${original.trimEnd()}${original.trim() ? '\n\n' : ''}${CODEX_PROJECT_BLOCK}\n`;
    }
  }
  if (!updated.endsWith('\n')) updated += '\n';
  try {
    const parsed = parseToml(updated) as Record<string, unknown>;
    const servers = parsed.mcp_servers;
    const registration =
      typeof servers === 'object' && servers !== null
        ? Reflect.get(servers, 'clankerchat')
        : undefined;
    const legacyRegistration =
      typeof servers === 'object' && servers !== null
        ? Reflect.get(servers, 'clankchat')
        : undefined;
    if (!codexMcpRegistrationConfigured(registration) || legacyRegistration !== undefined) {
      throw new Error('MCP block was extended.');
    }
  } catch (error) {
    throw new ClankerChatError('SETUP_ERROR', 'Could not update the Codex configuration safely.', {
      path: target,
      cause: error instanceof Error ? error.message : String(error),
    });
  }
  if (updated === existing && existsSync(target)) return false;
  if (apply) {
    mkdirSync(path.dirname(target), { recursive: true });
    writeTextFileAtomic(target, updated);
  }
  return true;
}

function configureCodexHooks(codexHome: string, apply: boolean): boolean {
  const target = assertSafeWritePath(codexHome, 'hooks.json');
  const original = readText(target) ?? '{}\n';
  const parsed = parseJsonc(original, target) as Record<string, unknown>;
  const currentHooks = parsed.hooks;
  if (
    currentHooks !== undefined &&
    (typeof currentHooks !== 'object' || currentHooks === null || Array.isArray(currentHooks))
  ) {
    throw new ClankerChatError('SETUP_ERROR', 'Codex has an incompatible hooks value.', {
      path: target,
    });
  }
  const hooks = (currentHooks ?? {}) as Record<string, unknown>;
  let updated = original;
  for (const event of Object.keys(CODEX_HOOKS) as CodexHookEvent[]) {
    const current = hooks[event];
    if (current !== undefined && !Array.isArray(current)) {
      throw new ClankerChatError('SETUP_ERROR', 'Codex has an incompatible hook event value.', {
        path: target,
        event,
      });
    }
    const command = `clankerchat hook codex --event ${event}`;
    const legacyCommand = `clankchat hook codex --event ${event}`;
    const entries = (current ?? []) as unknown[];
    const expected = JSON.stringify(CODEX_HOOKS[event]);
    const legacy = expected.replace(command, legacyCommand);
    let expectedIndex = -1;
    let legacyIndex = -1;
    for (const [index, entry] of entries.entries()) {
      const encoded = JSON.stringify(entry);
      if (encoded === expected) {
        if (expectedIndex >= 0) {
          throw new ClankerChatError('SETUP_ERROR', 'A Codex hook entry is duplicated.', {
            path: target,
            event,
          });
        }
        expectedIndex = index;
        continue;
      }
      if (encoded === legacy) {
        if (legacyIndex >= 0) {
          throw new ClankerChatError('SETUP_ERROR', 'A legacy Codex hook entry is duplicated.', {
            path: target,
            event,
          });
        }
        legacyIndex = index;
        continue;
      }
      if (encoded.includes(command) || encoded.includes(legacyCommand)) {
        throw new ClankerChatError('SETUP_ERROR', 'A Codex hook entry was modified.', {
          path: target,
          event,
        });
      }
    }
    if (expectedIndex >= 0 && legacyIndex >= 0) {
      throw new ClankerChatError('SETUP_ERROR', 'Current and legacy Codex hooks both exist.', {
        path: target,
        event,
      });
    }
    const targetPath: Array<string | number> =
      legacyIndex >= 0
        ? ['hooks', event, legacyIndex, 'hooks', 0, 'command']
        : current === undefined
          ? ['hooks', event]
          : ['hooks', event, entries.length];
    const value =
      legacyIndex >= 0
        ? command
        : current === undefined
          ? [CODEX_HOOKS[event]]
          : CODEX_HOOKS[event];
    if (expectedIndex < 0) {
      updated = applyEdits(
        updated,
        modify(updated, targetPath, value, {
          formattingOptions: { insertSpaces: true, tabSize: 2 },
        }),
      );
    }
  }
  const content = updated.endsWith('\n') ? updated : `${updated}\n`;
  if (content === original && existsSync(target)) return false;
  if (apply) {
    mkdirSync(path.dirname(target), { recursive: true });
    writeTextFileAtomic(target, content, 0o600);
  }
  return true;
}

function assertCodexVersion(version: SetupCommandResult): void {
  if (version.status !== 0 || !codexVersionSupported(version.stdout)) {
    throw new ClankerChatError(
      'SETUP_ERROR',
      `Codex CLI ${CODEX_MINIMUM_VERSION} or newer is required.`,
      { status: version.status, version: version.stdout.trim(), stderr: version.stderr.trim() },
    );
  }
}

