function readText(target: string): string | null {
  try {
    return readFileSync(target, 'utf8');
  } catch (error) {
    if (error instanceof Error && Reflect.get(error, 'code') === 'ENOENT') return null;
    throw error;
  }
}

function writeProjectFile(
  root: string,
  relative: string,
  content: string,
  ownedMarker?: string,
  apply = true,
): boolean {
  const target = assertSafeWritePath(root, relative);
  const existing = readText(target);
  if (existing === content) return false;
  if (existing !== null && ownedMarker && !existing.startsWith(ownedMarker)) {
    throw new ClankChatError('SETUP_ERROR', 'Refusing to overwrite an unowned integration file.', {
      path: target,
    });
  }
  if (apply) {
    mkdirSync(path.dirname(target), { recursive: true });
    writeTextFileAtomic(target, content);
  }
  return true;
}

function removeOwnedBlock(content: string, start: string, end: string): string {
  let updated = content;
  while (updated.includes(start) || updated.includes(end)) {
    const begin = updated.indexOf(start);
    const finish = updated.indexOf(end);
    if (begin < 0 || finish < begin) {
      throw new ClankChatError('SETUP_ERROR', 'An integration instruction marker is malformed.');
    }
    updated = `${updated.slice(0, begin)}${updated.slice(finish + end.length)}`;
  }
  return updated.replace(/\n{3,}/gu, '\n\n').trimEnd();
}

function oldKey(value: string): boolean {
  const key = value.toLowerCase();
  return key === 'sametree' || key.startsWith('sametree.') || key.startsWith('sametree_');
}

function oldValue(value: string): boolean {
  const item = value.toLowerCase().replaceAll('\\', '/');
  const basename = path.posix.basename(item);
  return (
    item === 'sametree' ||
    item === 'sametree-mcp' ||
    item === 'sametree@sametree' ||
    item.startsWith('sametree@') ||
    item.startsWith('.sametree/') ||
    item.includes('/.sametree/') ||
    basename === 'sametree-tui.ts' ||
    basename === 'sametree-tui.js' ||
    item.includes('generated by sametree')
  );
}

function oldEntry(value: unknown): boolean {
  if (typeof value === 'string') return oldValue(value);
  if (Array.isArray(value)) return value.some(oldEntry);
  if (typeof value !== 'object' || value === null) return false;
  return Object.entries(value).some(([key, entry]) => oldKey(key) || oldEntry(entry));
}

interface CleanupEdit {
  path: Array<string | number>;
  value: unknown;
}

function cleanupEdits(value: unknown, current: Array<string | number> = []): CleanupEdit[] {
  if (Array.isArray(value)) {
    const filtered = value.filter((entry) => !oldEntry(entry));
    if (filtered.length !== value.length) return [{ path: current, value: filtered }];
    return value.flatMap((entry, index) => cleanupEdits(entry, [...current, index]));
  }
  if (typeof value !== 'object' || value === null) return [];
  const edits: CleanupEdit[] = [];
  for (const [key, entry] of Object.entries(value)) {
    if (oldKey(key)) {
      edits.push({ path: [...current, key], value: undefined });
    } else {
      edits.push(...cleanupEdits(entry, [...current, key]));
    }
  }
  return edits;
}

function cleanJsoncFile(target: string, apply: boolean): boolean {
  const content = readText(target);
  if (content === null || !content.toLowerCase().includes('sametree')) return false;
  if (lstatSync(target).isSymbolicLink()) {
    throw new ClankChatError('SETUP_ERROR', 'Refusing to update a symlinked settings file.', {
      path: target,
    });
  }
  const errors: ParseError[] = [];
  const value: unknown = parse(content, errors, { allowTrailingComma: true });
  if (errors.length > 0) {
    throw new ClankChatError(
      'SETUP_ERROR',
      'Could not parse a settings file containing stale data.',
      {
        path: target,
      },
    );
  }
  let updated = content;
  const edits = cleanupEdits(value).sort((left, right) => right.path.length - left.path.length);
  if (edits.length === 0) return false;
  for (const edit of edits) {
    updated = applyEdits(
      updated,
      modify(updated, edit.path, edit.value, {
        formattingOptions: { insertSpaces: true, tabSize: 2 },
      }),
    );
  }
  if (updated === content) return false;
  if (apply) writeTextFileAtomic(target, updated);
  return true;
}

function setJsoncValue(
  root: string,
  relative: string,
  targetPath: Array<string | number>,
  value: unknown,
  apply = true,
): boolean {
  const target = assertSafeWritePath(root, relative);
  const original = readText(target) ?? '{}\n';
  parseJsonc(original, target);
  const updated = applyEdits(
    original,
    modify(original, targetPath, value, {
      formattingOptions: { insertSpaces: true, tabSize: 2 },
    }),
  );
  if (updated === original && existsSync(target)) return false;
  if (apply) {
    mkdirSync(path.dirname(target), { recursive: true });
    writeTextFileAtomic(target, updated.endsWith('\n') ? updated : `${updated}\n`);
  }
  return true;
}

function parseJsonc(content: string, target: string): unknown {
  const errors: ParseError[] = [];
  const value: unknown = parse(content, errors, { allowTrailingComma: true });
  if (errors.length > 0 || typeof value !== 'object' || value === null || Array.isArray(value)) {
    throw new ClankChatError('SETUP_ERROR', 'Could not parse an integration settings file.', {
      path: target,
    });
  }
  return value;
}

function nestedValue(value: unknown, targetPath: string[]): unknown {
  let current = value;
  for (const segment of targetPath) {
    current =
      typeof current === 'object' && current !== null ? Reflect.get(current, segment) : undefined;
  }
  return current;
}

function addArrayValue(
  root: string,
  relative: string,
  targetPath: string[],
  value: string,
  apply = true,
): boolean {
  const target = assertSafeWritePath(root, relative);
  const original = readText(target) ?? '{}\n';
  const current = nestedValue(parseJsonc(original, target), targetPath);
  if (current !== undefined && !Array.isArray(current)) {
    throw new ClankChatError('SETUP_ERROR', 'An integration list has an incompatible value.', {
      path: target,
      setting: targetPath.join('.'),
    });
  }
  const entries = current ?? [];
  if (
    entries.some(
      (entry) =>
        entry === value || (Array.isArray(entry) && entry.length > 0 && entry[0] === value),
    )
  )
    return false;
  return setJsoncValue(root, relative, targetPath, [...entries, value], apply);
}

function configureOpenCodeServer(root: string, relative: string, apply = true): boolean {
  const target = assertSafeWritePath(root, relative);
  const original = readText(target) ?? '{}\n';
  const current = nestedValue(parseJsonc(original, target), ['mcp', 'clankchat']);
  if (current !== undefined && JSON.stringify(current) !== JSON.stringify(MCP_SERVER)) {
    throw new ClankChatError(
      'SETUP_ERROR',
      'OpenCode already has a conflicting clankchat MCP server.',
      { path: target },
    );
  }
  return setJsoncValue(root, relative, ['mcp', 'clankchat'], MCP_SERVER, apply);
}

function configureCodexProject(root: string, apply: boolean): boolean {
  const target = assertSafeWritePath(root, '.codex/config.toml');
  const original = readText(target) ?? '';
  const start = original.indexOf(CODEX_PROJECT_START);
  const end = original.indexOf(CODEX_PROJECT_END);
  if (
    start < 0 !== end < 0 ||
    (start >= 0 &&
      (end < start ||
        original.indexOf(CODEX_PROJECT_START, start + CODEX_PROJECT_START.length) >= 0 ||
        original.indexOf(CODEX_PROJECT_END, end + CODEX_PROJECT_END.length) >= 0))
  ) {
    throw new ClankChatError('SETUP_ERROR', 'The Codex integration marker is malformed.', {
      path: target,
    });
  }
  let updated: string;
  if (start >= 0) {
    updated = `${original.slice(0, start)}${CODEX_PROJECT_BLOCK}${original.slice(
      end + CODEX_PROJECT_END.length,
    )}`;
  } else {
    let parsed: Record<string, unknown>;
    try {
      parsed = parseToml(original) as Record<string, unknown>;
    } catch (error) {
      throw new ClankChatError('SETUP_ERROR', 'Could not parse the Codex configuration.', {
        path: target,
        cause: error instanceof Error ? error.message : String(error),
      });
    }
    const servers = parsed.mcp_servers;
    if (
      typeof servers === 'object' &&
      servers !== null &&
      Reflect.get(servers, 'clankchat') !== undefined
    ) {
      throw new ClankChatError(
        'SETUP_ERROR',
        'Codex already has a conflicting clankchat MCP server.',
        {
          path: target,
        },
      );
    }
    updated = `${original.trimEnd()}${original.trim() ? '\n\n' : ''}${CODEX_PROJECT_BLOCK}\n`;
  }
  if (!updated.endsWith('\n')) updated += '\n';
  try {
    const parsed = parseToml(updated) as Record<string, unknown>;
    const servers = parsed.mcp_servers;
    const registration =
      typeof servers === 'object' && servers !== null
        ? Reflect.get(servers, 'clankchat')
        : undefined;
    if (!codexMcpRegistrationConfigured(registration)) throw new Error('MCP block was extended.');
  } catch (error) {
    throw new ClankChatError('SETUP_ERROR', 'Could not update the Codex configuration safely.', {
      path: target,
      cause: error instanceof Error ? error.message : String(error),
    });
  }
  if (updated === original && existsSync(target)) return false;
  if (apply) {
    mkdirSync(path.dirname(target), { recursive: true });
    writeTextFileAtomic(target, updated);
  }
  return true;
}

function hookCommand(entry: unknown): string | null {
  if (typeof entry !== 'object' || entry === null || Array.isArray(entry)) return null;
  const hooks = Reflect.get(entry, 'hooks');
  if (!Array.isArray(hooks) || hooks.length !== 1) return null;
  const hook = hooks[0];
  if (typeof hook !== 'object' || hook === null || Array.isArray(hook)) return null;
  const command = Reflect.get(hook, 'command');
  return typeof command === 'string' ? command : null;
}

function configureCodexHooks(codexHome: string, apply: boolean): boolean {
  const target = assertSafeWritePath(codexHome, 'hooks.json');
  const original = readText(target) ?? '{}\n';
  const parsed = parseJsonc(original, target) as Record<string, unknown>;
  const currentHooks = parsed.hooks;
  if (currentHooks !== undefined && (typeof currentHooks !== 'object' || currentHooks === null)) {
    throw new ClankChatError('SETUP_ERROR', 'Codex has an incompatible hooks value.', {
      path: target,
    });
  }
  const hooks = { ...((currentHooks ?? {}) as Record<string, unknown>) };
  for (const event of Object.keys(CODEX_HOOKS) as CodexHookEvent[]) {
    const current = hooks[event];
    if (current !== undefined && !Array.isArray(current)) {
      throw new ClankChatError('SETUP_ERROR', 'Codex has an incompatible hook event value.', {
        path: target,
        event,
      });
    }
    const command = `clankchat hook codex --event ${event}`;
    const entries = (current ?? []) as unknown[];
    const unrelated = entries.filter((entry) => hookCommand(entry) !== command);
    const combined = entries.find((entry) => {
      if (typeof entry !== 'object' || entry === null || Array.isArray(entry)) return false;
      const handlers = Reflect.get(entry, 'hooks');
      return (
        Array.isArray(handlers) &&
        handlers.length !== 1 &&
        handlers.some(
          (handler) =>
            typeof handler === 'object' &&
            handler !== null &&
            Reflect.get(handler, 'command') === command,
        )
      );
    });
    if (combined) {
      throw new ClankChatError('SETUP_ERROR', 'A clankchat Codex hook shares an unowned entry.', {
        path: target,
        event,
      });
    }
    hooks[event] = [...unrelated, CODEX_HOOKS[event]];
  }
  const updated = applyEdits(
    original,
    modify(original, ['hooks'], hooks, {
      formattingOptions: { insertSpaces: true, tabSize: 2 },
    }),
  );
  const content = updated.endsWith('\n') ? updated : `${updated}\n`;
  if (content === original && existsSync(target)) return false;
  if (apply) {
    mkdirSync(path.dirname(target), { recursive: true });
    writeTextFileAtomic(target, content, 0o600);
  }
  return true;
}

function assertCodexVersion(version: SetupCommandResult): void {
  if (version.status !== 0 || !codexVersionSupported(version.stdout)) {
    throw new ClankChatError(
      'SETUP_ERROR',
      `Codex CLI ${CODEX_MINIMUM_VERSION} or newer is required.`,
      { status: version.status, version: version.stdout.trim(), stderr: version.stderr.trim() },
    );
  }
}

function assertCodexHooksEnabled(features: SetupCommandResult): void {
  if (features.status !== 0 || !codexHooksFeatureEnabled(features.stdout)) {
    throw new ClankChatError('SETUP_ERROR', 'Codex hooks must be enabled.', {
      status: features.status,
      hooks: features.stdout.trim(),
      stderr: features.stderr.trim(),
    });
  }
}

function configureCodex(root: string, codexHome: string): void {
  configureCodexHooks(codexHome, true);
  configureCodexProject(root, true);
}

