  it('rejects every contender when a stale lock exists', async () => {
    const { root, home } = fixture();
    const lockPath = path.join(
      resolveRepository(root).commonGitDirectory,
      'clankchat',
      'setup.lock',
    );
    mkdirSync(path.dirname(lockPath), { recursive: true });
    writeFileSync(lockPath, `${JSON.stringify({ processId: 2_147_483_647, startedAt: 0 })}\n`);
    const setupModule = pathToFileURL(path.resolve('dist/setup.js')).href;
    const source = `
      import { setup } from ${JSON.stringify(setupModule)};
      const wait = () => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 300);
      const commandRunner = (_command, args) => {
        if (args.join(" ") === "mcp get clankerchat") {
          wait();
          return { status: 1, stdout: 'No MCP server named "clankerchat".', stderr: "" };
        }
        if (args.includes("--json")) return { status: 0, stdout: "[]", stderr: "" };
        return { status: 0, stdout: "", stderr: "" };
      };
      try {
        setup({ cwd: ${JSON.stringify(root)}, homeDirectory: ${JSON.stringify(home)}, claude: true, commandRunner });
      } catch (error) {
        process.stderr.write(error instanceof Error ? error.message : String(error));
        process.exitCode = 1;
      }
    `;
    const run = () =>
      new Promise<{ code: number | null; stderr: string }>((resolve) => {
        const child = spawn(process.execPath, ['--input-type=module', '--eval', source], {
          stdio: ['ignore', 'ignore', 'pipe'],
        });
        let stderr = '';
        child.stderr.setEncoding('utf8');
        child.stderr.on('data', (chunk: string) => {
          stderr += chunk;
        });
        child.once('exit', (code) => resolve({ code, stderr }));
      });

    const results = await Promise.all([run(), run()]);
    expect(results.map((result) => result.code)).toEqual([1, 1]);
    expect(results.map((result) => result.stderr)).toEqual([
      expect.stringMatching(/previous setup/u),
      expect.stringMatching(/previous setup/u),
    ]);
  });

